.global LibcForward\ordinal
.type LibcForward\ordinal, %function
LibcForward\ordinal:
    push {r0-r3, ip, lr}
    mov r0, #(\ordinal & 0xff)
    orr r0, r0, #(\ordinal & 0xff00)
    bl LibcResolve
    mov ip, r0
    pop {r0-r3}
    add sp, sp, #4
    pop {lr}
    bx ip
.size LibcForward\ordinal, .-LibcForward\ordinal
.endm
