.syntax unified
.arm
.text
.macro FORWARD ordinal
.global AudioForward\ordinal
.type AudioForward\ordinal, %function
AudioForward\ordinal:
    push {r0-r3, ip, lr}
    mov r0, #\ordinal
    mov r1, sp
    bl AudioResolve
    mov ip, r0
    pop {r0-r3}
    add sp, sp, #4
    pop {lr}
    bx ip
.size AudioForward\ordinal, .-AudioForward\ordinal
.endm
